package com.agristock.service;

import java.time.LocalDate;
import com.agristock.model.Models.YieldRecord;

/** Loads demo data made for testing (the proposal states the system is tested with group-made sample data). */
public final class SampleData {
    private SampleData() {}

    public static void load(AgriStockSystem s) {
        // Clear existing data so sample data can be reloaded on a non-empty system.
        s.farmers.clear();
        s.farms.clear();
        s.crops.clear();
        s.batches.clear();
        s.stockRecords.clear();
        s.inspectionQueue.clear();
        s.stock.clear();
        s.expiryHeap.clear();
        s.pendingSales.clear();
        s.sales.clear();
        s.deliveries.clear();
        s.deliveryQueue.clear();
        s.spoilage.clear();
        s.yields.clear();
        s.rotationQueue.clear();
        s.saleCounter = 0;
        s.deliveryCounter = 0;
        s.spoilageCounter = 0;

        LocalDate t = s.today();
        // Farmer IDs are generated by the system.
        String f1 = s.nextFarmerId();
        String f2 = s.nextFarmerId();
        String f3 = s.nextFarmerId();
        s.registerFarmer(f1, "Juan Dela Cruz", "0917-111-2222");
        s.registerFarmer(f2, "Maria Santos", "0918-333-4444");
        s.registerFarmer(f3, "Pedro Reyes", "0919-555-6666");
        s.registerFarm("FARM-A", "Dela Cruz Farm", "Nueva Ecija", 2.5);
        s.registerFarm("FARM-B", "Santos Orchard", "Batangas", 1.8);
        s.registerCrop("Rice", "Jasmine", "Grain");
        s.registerCrop("Tomato", "Diamante", "Vegetable");
        s.registerCrop("Mango", "Carabao", "Fruit");
        s.registerCrop("Corn", "Yellow", "Grain");
        s.registerCrop("Eggplant", "Long Purple", "Vegetable");
        s.registerCrop("Banana", "Lakatan", "Fruit");

        s.createHarvestBatch("B-1001", "FARM-A", "Plot 1", "Rice", "Jasmine", "Ramon", f1, t.minusDays(30), t.plusDays(150), 20, "sack (50 kg)");
        s.createHarvestBatch("B-1002", "FARM-A", "Plot 2", "Tomato", "Diamante", "Liza", f1, t.minusDays(6), t.plusDays(4), 300, "kg");
        s.createHarvestBatch("B-1003", "FARM-B", "Block 4", "Mango", "Carabao", "Ben", f2, t.minusDays(8), t.plusDays(9), 250, "kg");
        s.createHarvestBatch("B-1004", "FARM-A", "Plot 3", "Corn", "Yellow", "Ramon", f3, t.minusDays(15), t.plusDays(100), 1.5, "ton");
        s.createHarvestBatch("B-1005", "FARM-B", "Block 1", "Eggplant", "Long Purple", "Ben", f2, t.minusDays(20), t.minusDays(2), 120, "kg");
        s.createHarvestBatch("B-1006", "FARM-B", "Block 2", "Banana", "Lakatan", "Liza", f2, t.minusDays(3), t.plusDays(8), 200, "kg");
        s.recordHarvest(f1, "Rice", 1000, t.minusDays(30));
        s.recordHarvest(f1, "Tomato", 300, t.minusDays(6));
        s.recordHarvest(f2, "Mango", 250, t.minusDays(8));

        s.recordHarvestedStock("B-1001", 1000, 50, "A", "N/A", "Broken grains");
        s.recordHarvestedStock("B-1002", 300, 15, "A", "Ripe", "Bruised fruit");
        s.recordHarvestedStock("B-1003", 250, 0, "B", "Ripe", "");
        s.recordHarvestedStock("B-1004", 1500, 30, "A", "N/A", "Moldy cobs");
        s.recordHarvestedStock("B-1005", 120, 0, "B", "Overripe", "");
        s.recordHarvestedStock("B-1006", 200, 0, "A", "Unripe", "");

        s.inspectBatch("ACCEPTED", "A", "", 48);
        s.inspectBatch("ACCEPTED", "A", "", 55);
        s.inspectBatch("DOWNGRADED", "B", "Minor blemishes, sold as grade B", 70);
        s.inspectBatch("ACCEPTED", "A", "", 22);
        s.inspectBatch("ACCEPTED", "B", "", 40);          // B-1006 stays in the inspection queue

        s.assignLocation("B-1001", 2, 900, t.minusDays(29), "22\u00B0C, 60% RH");
        s.assignLocation("B-1002", 0, 285, t.minusDays(5), "10\u00B0C, 90% RH");
        s.assignLocation("B-1003", 1, 250, t.minusDays(7), "13\u00B0C, 85% RH");
        s.assignLocation("B-1004", 4, 1470, t.minusDays(14), "Ambient, ventilated");

        s.createSale("Metro Market", "B-1002", 100, 60);
        s.createSale("Golden Grains Trading", "B-1001", 200, 62);
        s.createSale("Fresh Mart", "B-1003", 80, 95);
        s.confirmSale();
        s.confirmSale();
        s.scheduleDelivery(s.sales.linearSearch(x -> x.ref.equals("SO-0001")), t.plusDays(2), "Truck TRK-101", "Metro Market, Quezon City", 1);
        s.scheduleDelivery(s.sales.linearSearch(x -> x.ref.equals("SO-0002")), t.plusDays(5), "Van VAN-205", "Golden Grains, Cabanatuan", 2);

        s.recordSpoilage("B-1002", 12, "Spoiled during transport", "inventory");
        double[][] rice = {{4200, 4000}, {4500, 4300}, {4100, 4400}, {4800, 4600}, {5000, 4900}};
        double[][] tomato = {{1200, 1100}, {1350, 1300}, {1100, 1250}, {1500, 1400}, {1450, 1500}};
        String[] seasons = {"2024 Dry", "2024 Wet", "2025 Dry", "2025 Wet", "2026 Dry"};
        for (int i = 0; i < seasons.length; i++) {
            s.yields.add(new YieldRecord("Rice", seasons[i], rice[i][0], rice[i][1]));
            s.yields.add(new YieldRecord("Tomato", seasons[i], tomato[i][0], tomato[i][1]));
        }
        s.logTransaction("SAMPLE_DATA", "-", "Sample data loaded");
    }
}
